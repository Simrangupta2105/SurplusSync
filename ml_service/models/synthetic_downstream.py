def validate_no_leakage(columns: Sequence[str]) -> None:
    """Validate that none of the forbidden outcome columns appear in the input features."""
    detected = set(columns).intersection(FORBIDDEN_LEAKAGE_COLUMNS)
    if detected:
        raise LeakageError(
            f"DATA LEAKAGE DETECTED in Task 6 Classifier! The following forbidden outcome "
            f"columns were present in feature set: {sorted(list(detected))}. "
            f"Allowed features: {ALLOWED_CLASSIFIER_FEATURES}"
        )


class MajorityClassifier(BaseEstimator, ClassifierMixin):
    """Majority class baseline (always predicts 'Low')."""

    def __init__(self) -> None:
        self.majority_class_: str = "Low"
        self.classes_: np.ndarray = np.array(TARGET_CLASSES)

    def fit(self, X: Any, y: Sequence[str]) -> MajorityClassifier:
        vals, counts = np.unique(y, return_counts=True)
        self.majority_class_ = str(vals[np.argmax(counts)])
        return self

    def predict(self, X: Any) -> np.ndarray:
        n = len(X)
        return np.full(n, self.majority_class_, dtype=object)

    def predict_proba(self, X: Any) -> np.ndarray:
        n = len(X)
        probs = np.zeros((n, len(self.classes_)))
        idx = list(self.classes_).index(self.majority_class_)
        probs[:, idx] = 1.0
        return probs


class HeuristicOverOrderClassifier(BaseEstimator, ClassifierMixin):
    """Simple operational rule baseline based on over_order_ratio = Purchase / Forecast."""

    def __init__(self, low_threshold: float = 1.02, high_threshold: float = 1.10) -> None:
        self.low_threshold = low_threshold
        self.high_threshold = high_threshold
        self.classes_: np.ndarray = np.array(TARGET_CLASSES)

    def fit(self, X: pd.DataFrame, y: Sequence[str]) -> HeuristicOverOrderClassifier:
        # Thresholds can be tuned or kept as standard business rules
        return self

    def predict(self, X: pd.DataFrame) -> np.ndarray:
        ratio = X["over_order_ratio"].values
        preds = np.full(len(X), "Medium", dtype=object)
        preds[ratio < self.low_threshold] = "Low"
        preds[ratio >= self.high_threshold] = "High"
        return preds

    def predict_proba(self, X: pd.DataFrame) -> np.ndarray:
        preds = self.predict(X)
        n = len(X)
        probs = np.zeros((n, len(self.classes_)))
        for i, c in enumerate(self.classes_):
            probs[preds == c, i] = 0.80
            probs[preds != c, i] = 0.10
        return probs


def generate_out_of_fold_demand_forecasts(
    panel_df: pd.DataFrame,
    test_cutoff: str = "2025-10-03",
    random_seed: int = 42,
) -> pd.DataFrame:
    """Generate strictly out-of-fold demand forecasts on train pool and test set.

    Uses HistGradientBoostingDemandModel across rolling origin folds for training pool,
    and out-of-sample forecast for the untouched test set.
    """
    df = panel_df.copy()
    if not pd.api.types.is_datetime64_any_dtype(df["Date"]):
        df["Date"] = pd.to_datetime(df["Date"])

    train_pool_df, test_df = split_train_test(df, test_cutoff=test_cutoff, test_days=90)

    df["forecast_demand"] = 0.0

    # 1. Generate OOF forecasts on train pool using 4-fold RollingOriginSplitter
    splitter = RollingOriginSplitter(n_splits=4, horizon=28, step=28, test_cutoff=test_cutoff)
    splits = list(splitter.split_series(train_pool_df))

    # To ensure every train row gets an out-of-fold forecast, use expanding windows
    first_split_train_end = splits[0][2].train_end

    # Pre-train baseline on earliest period
    early_mask = train_pool_df["Date"] <= first_split_train_end
    y_early, X_early = get_target_and_covariates(train_pool_df[early_mask])
    early_model = HistGradientBoostingDemandModel(max_iter=50, random_state=random_seed).fit(X_early, y_early)

    # Apply early model to earliest dates
    df.loc[df["Date"] <= first_split_train_end, "forecast_demand"] = early_model.predict(X_early)

    # For subsequent rolling test folds, predict strictly out-of-fold
    for train_fold, test_fold, _ in splits:
        y_tr, X_tr = get_target_and_covariates(train_fold)
        m = HistGradientBoostingDemandModel(max_iter=50, random_state=random_seed).fit(X_tr, y_tr)
        _, X_te = get_target_and_covariates(test_fold)
        test_dates = test_fold["Date"].unique()
        mask = df["Date"].isin(test_dates)
        df.loc[mask, "forecast_demand"] = m.predict(X_te)

    # 2. Fit on full train pool and predict out-of-sample on untouched test set
    y_full_tr, X_full_tr = get_target_and_covariates(train_pool_df)
    final_demand_model = HistGradientBoostingDemandModel(max_iter=60, random_state=random_seed).fit(
        X_full_tr, y_full_tr
    )

    _, X_test = get_target_and_covariates(test_df)
    test_mask = df["Date"] >= pd.to_datetime(test_cutoff)
    df.loc[test_mask, "forecast_demand"] = final_demand_model.predict(X_test)

    # Guard against negative or zero demand forecast
    df["forecast_demand"] = np.maximum(df["forecast_demand"], 1.0)
    df["over_order_ratio"] = df["Purchase_Quantity"] / df["forecast_demand"]
    df["Day_Of_Week"] = df["Date"].dt.dayofweek

    return df


def prepare_classifier_dataset(df_with_forecasts: pd.DataFrame) -> Tuple[pd.DataFrame, pd.Series]:
    """Validate and extract allowed classifier features and Waste_Level target."""
    validate_no_leakage(ALLOWED_CLASSIFIER_FEATURES)
    X = df_with_forecasts[ALLOWED_CLASSIFIER_FEATURES].copy()
    y = df_with_forecasts["Waste_Level"].copy()
    return X, y


def train_and_evaluate_waste_classifiers(
    panel_df_with_forecasts: pd.DataFrame,
    test_cutoff: str = "2025-10-03",
    random_seed: int = 42,
) -> Tuple[Dict[str, Any], pd.DataFrame, Any]:
    """Train candidate waste classifiers and evaluate on the untouched test set."""
    df = panel_df_with_forecasts.copy()
    train_mask = df["Date"] < pd.to_datetime(test_cutoff)
    test_mask = df["Date"] >= pd.to_datetime(test_cutoff)

    X, y = prepare_classifier_dataset(df)

    X_train, y_train = X[train_mask], y[train_mask]
    X_test, y_test = X[test_mask], y[test_mask]

    # Preprocessing pipeline
    numeric_features = [
        "Purchase_Quantity", "forecast_demand", "over_order_ratio",
        "Shelf_Life_Days", "Storage_Temperature", "Temperature_C",
        "Day_Of_Week", "Lead_Time_Days",
    ]
    categorical_features = ["Food_Category", "Business_Type", "Weather", "Promotion", "Is_Holiday"]

    preprocessor = ColumnTransformer(
        transformers=[
            ("num", StandardScaler(), numeric_features),
            ("cat", OneHotEncoder(handle_unknown="ignore", sparse_output=False), categorical_features),
        ]
    )

    # 1. Majority Classifier Baseline
    maj = MajorityClassifier().fit(X_train, y_train)

    # 2. Heuristic Rule Classifier Baseline
    rule = HeuristicOverOrderClassifier().fit(X_train, y_train)

    # 3. Logistic Regression (balanced)
    log_reg = Pipeline([
        ("prep", preprocessor),
        ("clf", LogisticRegression(class_weight="balanced", max_iter=500, random_state=random_seed)),
    ]).fit(X_train, y_train)

    # 4. HistGradientBoosting (balanced)
    hgb_clf = Pipeline([
        ("prep", preprocessor),
        ("clf", HistGradientBoostingClassifier(class_weight="balanced", random_state=random_seed, max_iter=60)),
    ]).fit(X_train, y_train)

    # 5. LightGBM Classifier (balanced)
    lgb_clf = Pipeline([
        ("prep", preprocessor),
        ("clf", lgb.LGBMClassifier(
            class_weight="balanced",
            random_state=random_seed,
            n_estimators=60,
            learning_rate=0.08,
            verbose=-1,
        )),
    ]).fit(X_train, y_train)

    candidate_models = {
        "Majority_Baseline": maj,
        "Heuristic_OverOrder_Rule": rule,
        "Logistic_Regression": log_reg,
        "HistGradientBoosting": hgb_clf,
        "LightGBM": lgb_clf,
    }

    eval_records = []
    best_macro_f1 = -1.0
    best_model_name = ""
    best_model_obj = None

    for name, model in candidate_models.items():
        y_pred = model.predict(X_test)
        macro_f1 = float(f1_score(y_test, y_pred, average="macro", zero_division=0))
        weighted_f1 = float(f1_score(y_test, y_pred, average="weighted", zero_division=0))
        acc = float(accuracy_score(y_test, y_pred))

        # Per-class recall
        prec, rec, f1_cls, supp = precision_recall_fscore_support(
            y_test, y_pred, labels=TARGET_CLASSES, zero_division=0
        )

        record = {
            "model": name,
            "macro_f1": macro_f1,
            "weighted_f1": weighted_f1,
            "accuracy": acc,
            "recall_low": float(rec[0]),
            "recall_medium": float(rec[1]),
            "recall_high": float(rec[2]),
            "precision_high": float(prec[2]),
        }
        eval_records.append(record)

        if macro_f1 > best_macro_f1:
            best_macro_f1 = macro_f1
            best_model_name = name
            best_model_obj = model

    results_df = pd.DataFrame(eval_records).sort_values("macro_f1", ascending=False).reset_index(drop=True)

    # Compute detailed metrics for best model
    best_y_pred = best_model_obj.predict(X_test)
    best_cm = confusion_matrix(y_test, best_y_pred, labels=TARGET_CLASSES)

    details = {
        "best_model_name": best_model_name,
        "best_macro_f1": best_macro_f1,
        "results_table": results_df,
        "confusion_matrix": best_cm.tolist(),
        "classes": TARGET_CLASSES,
        "note": "Labels are generated by clean synthetic rule (Low < 0.015, Med 0.015-0.085, High >= 0.085), so accuracy will appear higher than on real noisy operational data.",
    }

    return details, results_df, best_model_obj


def run_retrospective_reorder_simulation(
    panel_df_with_forecasts: pd.DataFrame,
    test_cutoff: str = "2025-10-03",
    residual_std: float = 25.44,
) -> Dict[str, Any]:
    """Run retrospective counterfactual reorder simulation comparing AI policy against actual purchases.

    Simulation formula:
      recommended = forecast_demand + z * residual_std * sqrt(lead_time)
      capped at 0.70 * Shelf_Life_Days * forecast_demand.
    """
    df = panel_df_with_forecasts.copy()
    test_slice = df[df["Date"] >= pd.to_datetime(test_cutoff)].copy()

    service_levels = [0.80, 0.90, 0.95]
    simulation_results = []

    # Actual historical operator metrics
    actual_P = test_slice["Purchase_Quantity"].values
    actual_D = test_slice["Daily_Demand"].values

    actual_over_purchase = float(np.sum(np.maximum(0, actual_P - actual_D)))
    actual_stockout_rows = int(np.sum(actual_P < actual_D))
    actual_stockout_rate = float(actual_stockout_rows / len(test_slice))
    actual_lost_sales = float(np.sum(np.maximum(0, actual_D - actual_P)))
    actual_total_purchased = float(np.sum(actual_P))

    simulation_results.append({
        "policy": "Actual_Historical_Purchases",
        "service_level": "N/A",
        "total_purchased_units": actual_total_purchased,
        "over_purchase_units": actual_over_purchase,
        "stockout_rows": actual_stockout_rows,
        "stockout_rate": actual_stockout_rate,
        "lost_sales_units": actual_lost_sales,
        "shelf_cap_applied_count": 0,
    })

    # AI Policy simulations
    for sl in service_levels:
        ai_recommendations = []
        shelf_caps_applied = 0

        for _, row in test_slice.iterrows():
            rec = compute_recommended_reorder(
                forecast_demand=float(row["forecast_demand"]),
                forecast_residual_std=residual_std,
                shelf_life_days=float(row["Shelf_Life_Days"]),
                service_level=sl,
                lead_time_days=float(row["Lead_Time_Days"]),
                shelf_life_cap_ratio=0.70,
                current_on_hand=0.0,
                on_order=0.0,
            )
            ai_recommendations.append(rec.suggested_qty)
            if rec.shelf_cap_applied:
                shelf_caps_applied += 1

        ai_P = np.array(ai_recommendations)
        ai_over_purchase = float(np.sum(np.maximum(0, ai_P - actual_D)))
        ai_stockout_rows = int(np.sum(ai_P < actual_D))
        ai_stockout_rate = float(ai_stockout_rows / len(test_slice))
        ai_lost_sales = float(np.sum(np.maximum(0, actual_D - ai_P)))
        ai_total_purchased = float(np.sum(ai_P))

        simulation_results.append({
            "policy": f"AI_Recommended_{int(sl*100)}%",
            "service_level": sl,
            "total_purchased_units": ai_total_purchased,
            "over_purchase_units": ai_over_purchase,
            "stockout_rows": ai_stockout_rows,
            "stockout_rate": ai_stockout_rate,
            "lost_sales_units": ai_lost_sales,
            "shelf_cap_applied_count": shelf_caps_applied,
        })

    sim_df = pd.DataFrame(simulation_results)

    # Counterfactual waste reduction estimate (based on actual test discard rate)
    test_actual_waste = float(np.sum(test_slice["Waste_Quantity"].values))
    # Empirical remaining discard factor
    discard_factor = test_actual_waste / actual_over_purchase if actual_over_purchase > 0 else 0.20
    ai_90_over = sim_df.loc[sim_df["policy"] == "AI_Recommended_90%", "over_purchase_units"].values[0]
    estimated_waste_ai_90 = ai_90_over * discard_factor
    waste_reduction_pct = (test_actual_waste - estimated_waste_ai_90) / test_actual_waste * 100.0

    return {
        "simulation_table": sim_df,
        "assumptions": COUNTERFACTUAL_ASSUMPTIONS,
        "counterfactual_waste_estimate": {
            "status": "COUNTERFACTUAL ESTIMATE",
            "actual_waste_units": test_actual_waste,
            "estimated_ai_90_waste_units": estimated_waste_ai_90,
            "estimated_reduction_pct": waste_reduction_pct,
            "discard_ratio_factor": discard_factor,
        },
    }


def save_models_to_registry(
    demand_model: Any,
    demand_metadata: Dict[str, Any],
    waste_classifier: Any,
    classifier_metadata: Dict[str, Any],
    registry_dir: Optional[Path | str] = None,
) -> Tuple[Path, Path]:
    """Save trained demand forecaster and waste classifier with complete JSON metadata into registry."""
    out_dir = Path(registry_dir) if registry_dir else SAVED_MODELS_DIR
    out_dir.mkdir(parents=True, exist_ok=True)

    # 1. Save Demand Model
    demand_model_path = out_dir / "best_synthetic_demand_model.joblib"
    joblib.dump(demand_model, demand_model_path)

    demand_meta_path = out_dir / "best_synthetic_demand_model_metadata.json"
    with open(demand_meta_path, "w", encoding="utf-8") as f:
        json.dump(demand_metadata, f, indent=2)

    # 2. Save Waste Classifier
    clf_model_path = out_dir / "best_synthetic_waste_classifier.joblib"
    joblib.dump(waste_classifier, clf_model_path)

    clf_meta_path = out_dir / "best_synthetic_waste_classifier_metadata.json"
    with open(clf_meta_path, "w", encoding="utf-8") as f:
        json.dump(classifier_metadata, f, indent=2)

    return demand_model_path, clf_model_path


def load_best(
    model_type: str = "demand",
    track: str = "synthetic",
    registry_dir: Optional[Path | str] = None,
) -> Tuple[Any, Dict[str, Any]]:
    """Load the best registered model and metadata."""
    r_dir = Path(registry_dir) if registry_dir else SAVED_MODELS_DIR
    prefix = "best_synthetic_" if track == "synthetic" else "best_"

    if model_type == "demand":
        m_path = r_dir / f"{prefix}demand_model.joblib"
        meta_path = r_dir / f"{prefix}demand_model_metadata.json"
    elif model_type == "classifier":
        m_path = r_dir / f"{prefix}waste_classifier.joblib"
        meta_path = r_dir / f"{prefix}waste_classifier_metadata.json"
    else:
        raise ValueError(f"Unknown model_type: {model_type}. Must be 'demand' or 'classifier'.")

    if not m_path.exists():
        raise FileNotFoundError(f"Model file not found at {m_path}")
    if not meta_path.exists():
        raise FileNotFoundError(f"Metadata file not found at {meta_path}")

    model = joblib.load(m_path)
    with open(meta_path, "r", encoding="utf-8") as f:
        metadata = json.load(f)

    return model, metadata


